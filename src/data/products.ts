export function getProducts(): Product[] {
  return initialProducts;
}

export function getProductBySlug(slug: string): Product | undefined {
  return initialProducts.find((p) => p.slug === slug || p.id === slug);
}

export function getFeaturedProducts(): Product[] {
  return initialProducts.filter((p) => p.featured);
}

export function getTrendingProducts(): Product[] {
  return initialProducts.filter((p) => p.trending);
}

export function getNewArrivals(): Product[] {
  return initialProducts.filter((p) => p.newArrival).reverse();
}

export function getProductsByCategory(category: string): Product[] {
  const norm = category.toLowerCase().trim();
  if (norm === "all" || !norm) return initialProducts;
  return initialProducts.filter(
    (p) =>
      p.category.toLowerCase() === norm ||
      p.subCategory?.toLowerCase() === norm ||
      p.occasion?.toLowerCase().includes(norm) ||
      (norm.includes("festive") && p.occasion?.toLowerCase() === "festive") ||
      (norm.includes("everyday") && (p.occasion?.toLowerCase() === "daily" || p.occasion?.toLowerCase().includes("casual"))) ||
      (norm.includes("ethnic") && (p.category.toLowerCase() === "kurtis" || p.subCategory?.toLowerCase().includes("ethnic")))
  );
}

export function searchProducts(query: string, filters?: ProductFilters): Product[] {
  let list = [...initialProducts];

  // Category filter
  if (filters?.category && filters.category.toLowerCase() !== "all") {
    list = getProductsByCategory(filters.category);
  }

  // Text search
  if (query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter((p) => {
      const matchName = p.name.toLowerCase().includes(q);
      const matchCat = p.category.toLowerCase().includes(q);
      const matchDesc = p.description.toLowerCase().includes(q);
      const matchFabric = p.fabric?.toLowerCase().includes(q) ?? false;
      const matchColor = p.color?.toLowerCase().includes(q) ?? false;
      const matchOccasion = p.occasion?.toLowerCase().includes(q) ?? false;
      const matchPattern = p.pattern?.toLowerCase().includes(q) ?? false;
      const matchBadge = p.badge?.toLowerCase().includes(q) ?? false;
      return matchName || matchCat || matchDesc || matchFabric || matchColor || matchOccasion || matchPattern || matchBadge;
    });
  }

  // Occasion filter
  if (filters?.occasion && filters.occasion !== "all") {
    list = list.filter((p) => p.occasion?.toLowerCase().includes(filters.occasion!.toLowerCase()));
  }

  // Sorting
  if (filters?.sortBy) {
    if (filters.sortBy === "price-asc") {
      list.sort((a, b) => a.price - b.price);
    } else if (filters.sortBy === "price-desc") {
      list.sort((a, b) => b.price - a.price);
    } else if (filters.sortBy === "newest") {
      list.sort((a, b) => initialProducts.indexOf(b) - initialProducts.indexOf(a));
    }
  }

  return list;
}

export function getRelatedProducts(currentSlug: string, limit: number = 3): Product[] {
  const current = getProductBySlug(currentSlug);
  return initialProducts
    .filter((p) => p.slug !== currentSlug)
    .sort((a, b) => {
      if (current && a.category === current.category) return -1;
      return 0;
    })
    .slice(0, limit);
}
